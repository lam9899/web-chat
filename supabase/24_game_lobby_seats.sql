-- 3. Dọn người mất kết nối, lời mời hết hạn và giữ ô số 1
-- luôn là ô của chủ phòng.
create or replace function public.normalize_game_channel_lobby(
  p_channel_id uuid
)
returns void
language plpgsql security definer set search_path = ''
as $$
declare
  next_host_id uuid;
begin
  update public.game_channel_invites
  set
    status = 'expired',
    responded_at = now()
  where channel_id = p_channel_id
    and status = 'pending'
    and expires_at <= now();

  delete from public.game_channel_players
  where channel_id = p_channel_id
    and last_seen_at <= now() - interval '2 minutes';

  if exists(
    select 1
    from public.game_channel_players
    where channel_id = p_channel_id
  ) and not exists(
    select 1
    from public.game_channel_players
    where channel_id = p_channel_id
      and seat_index = 0
  ) then
    select user_id
    into next_host_id
    from public.game_channel_players
    where channel_id = p_channel_id
    order by seat_index asc, joined_at asc
    limit 1;

    update public.game_channel_players
    set seat_index = 0
    where channel_id = p_channel_id
      and user_id = next_host_id;
  end if;
end;
$$;

-- 4. Trả danh sách người theo đúng vị trí ô chờ.
drop function if exists public.get_game_channel_players(uuid);

create function public.get_game_channel_players(
  p_channel_id uuid
)
returns table(
  id uuid,
  username text,
  avatar_url text,
  public_id bigint,
  role text,
  is_ready boolean,
  joined_at timestamptz,
  seat_index integer
)
language plpgsql stable security definer set search_path = ''
as $$
begin
  if not public.channel_can_view(p_channel_id, auth.uid()) then
    raise exception 'Bạn không có quyền xem kênh game này.'
      using errcode = '42501';
  end if;

  return query
  select
    p.user_id,
    coalesce(pr.username, 'Người chơi'),
    pr.avatar_url,
    pr.public_id,
    coalesce(ur.role, 'member'),
    p.is_ready,
    p.joined_at,
    p.seat_index
  from public.game_channel_players p
  join public.profiles pr on pr.id = p.user_id
  left join public.user_roles ur on ur.user_id = p.user_id
  where p.channel_id = p_channel_id
    and p.last_seen_at > now() - interval '2 minutes'
  order by p.seat_index asc;
end;
$$;

create or replace function public.get_game_channel_invites(
  p_channel_id uuid
)
returns table(
  invite_id bigint,
  seat_index integer,
  invitee_id uuid,
  username text,
  avatar_url text,
  public_id bigint,
  role text,
  inviter_username text,
  created_at timestamptz
)
language plpgsql stable security definer set search_path = ''
as $$
begin
  if not public.channel_can_view(p_channel_id, auth.uid()) then
    raise exception 'Bạn không có quyền xem lời mời của kênh game này.'
      using errcode = '42501';
  end if;

  return query
  select
    i.id,
    i.seat_index,
    i.invitee_id,
    coalesce(invitee.username, 'Người chơi'),
    invitee.avatar_url,
    invitee.public_id,
