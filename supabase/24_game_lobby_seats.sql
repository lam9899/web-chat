    coalesce(inviter.username, 'Một người bạn'),
    i.created_at
  from public.game_channel_invites i
  join public.profiles invitee on invitee.id = i.invitee_id
  join public.profiles inviter on inviter.id = i.inviter_id
  left join public.user_roles ur on ur.user_id = i.invitee_id
  where i.channel_id = p_channel_id
    and i.status = 'pending'
    and i.expires_at > now()
  order by i.seat_index asc;
