-- 1. Mỗi người chơi có một vị trí cố định trong phòng chờ.
alter table public.game_channel_players
  add column if not exists seat_index integer;

with ranked as (
  select
    channel_id,
    user_id,
    row_number() over (
      partition by channel_id
      order by joined_at asc, user_id asc
    ) - 1 as next_seat
  from public.game_channel_players
)
update public.game_channel_players p
set seat_index = ranked.next_seat
from ranked
where ranked.channel_id = p.channel_id
  and ranked.user_id = p.user_id
  and p.seat_index is null;

alter table public.game_channel_players
  alter column seat_index set not null;

alter table public.game_channel_players
  drop constraint if exists game_channel_players_seat_range;

alter table public.game_channel_players
  add constraint game_channel_players_seat_range
  check (seat_index between 0 and 31);

create unique index if not exists
game_channel_players_channel_seat_uidx
on public.game_channel_players(channel_id, seat_index);

-- 2. Lời mời bạn bè gắn với đúng ô chờ.
create table if not exists public.game_channel_invites (
  id bigint generated by default as identity primary key,
  channel_id uuid not null
    references public.channels(id) on delete cascade,
  seat_index integer not null check (seat_index between 0 and 31),
  inviter_id uuid not null
    references auth.users(id) on delete cascade,
  invitee_id uuid not null
    references auth.users(id) on delete cascade,
  status text not null default 'pending'
    check (status in (
      'pending', 'accepted', 'declined', 'cancelled', 'expired'
    )),
  created_at timestamptz not null default now(),
  expires_at timestamptz not null default (now() + interval '15 minutes'),
  responded_at timestamptz,
  constraint game_channel_invites_not_self
    check (inviter_id <> invitee_id)
);

create unique index if not exists
game_channel_invites_pending_seat_uidx
on public.game_channel_invites(channel_id, seat_index)
where status = 'pending';

create unique index if not exists
game_channel_invites_pending_user_uidx
on public.game_channel_invites(channel_id, invitee_id)
where status = 'pending';

create index if not exists
game_channel_invites_invitee_idx
on public.game_channel_invites(invitee_id, status, created_at desc);

alter table public.game_channel_invites enable row level security;
grant select on public.game_channel_invites to authenticated;

drop policy if exists "Visible game channel invites"
on public.game_channel_invites;
create policy "Visible game channel invites"
on public.game_channel_invites for select to authenticated
using (public.channel_can_view(channel_id, auth.uid()));

alter table public.game_channel_invites replica identity full;

do $$
